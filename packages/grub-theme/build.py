#!/usr/bin/env python3
"""Build the DOT OS GRUB theme into build/dot-os/.

Static text is pre-rendered to PNG (GRUB's own fonts are 1-bit bitmaps and
cannot letter-space); only the menu entries and the countdown use .pf2 fonts.
Layout follows design-system/boards/Grub.dc.html at a 32px margin; it is
anchored to the edges, so it holds at any resolution.
"""
import os
import shutil
import subprocess
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "tools"))
import boottokens as b  # noqa: E402

OUT = "build/dot-os"
PAD = 32
SEG, GAP, NSEG = 14, 2, 20
BAR_W = NSEG * SEG + (NSEG - 1) * GAP  # 318


def main():
    shutil.rmtree("build", ignore_errors=True)
    os.makedirs(OUT)
    t = b.T
    p = lambda name: os.path.join(OUT, name)  # noqa: E731

    # Fonts for the dynamic parts: menu entries (16) and the countdown (12).
    for size in (12, 16):
        subprocess.run(["grub-mkfont", "-s", str(size), "-o", p("space-mono-%d.pf2" % size), b.MONO], check=True)

    wm_w, wm_h = b.text(p("wordmark.png"), "DOT OS", b.DOTO, 36, "text-display", -0.02, axes=b.DOTO_AXES, height=36)
    tag_w, tag_h = b.label(p("tag.png"), "GRUB   arm64   UEFI")
    help_w, help_h = b.label(p("help.png"), "Up / down — select    Enter — boot    E — edit    C — console")
    boot_w, boot_h = b.label(p("booting-in.png"), "Booting in")

    # Selected entry inverts, like a menu's current item: a text-display bar,
    # radius-technical corners, built from nine pieces GRUB stretches.
    fill = t["text-display"]
    r = 4
    b.rect(p("select_c.png"), 1, 1, fill)
    b.rect(p("select_n.png"), 1, r, fill)
    b.rect(p("select_s.png"), 1, r, fill)
    b.rect(p("select_e.png"), r, 1, fill)
    b.rect(p("select_w.png"), r, 1, fill)
    for name, cx, cy in (("nw", r, r), ("ne", 0, r), ("sw", r, 0), ("se", 0, 0)):
        b.svg(p("select_%s.png" % name), r, r, '<circle cx="%d" cy="%d" r="%d" fill="%s"/>' % (cx, cy, r, fill))

    # No countdown bar: GRUB ignores a progress bar's height (it draws 28px
    # whatever the theme says), so the countdown is the label alone.

    theme = """# DOT OS GRUB theme. Generated by packages/grub-theme/build.py from design-system/tokens.json.
title-text: ""
desktop-color: "{black}"
terminal-font: "Space Mono Regular 16"
terminal-box: "terminal_*.png"
terminal-left: "{pad}"
terminal-top: "{pad}"
terminal-width: "100%-{pad2}"
terminal-height: "100%-{pad2}"

+ image {{ left = {pad} top = {pad} file = "wordmark.png" }}
+ image {{ left = 100%-{tag_x} top = {pad} file = "tag.png" }}

+ boot_menu {{
    left = {menu_x}
    top = 30%
    width = 560
    height = 50%
    item_font = "Space Mono Regular 16"
    item_color = "{secondary}"
    selected_item_font = "Space Mono Regular 16"
    selected_item_color = "{black}"
    selected_item_pixmap_style = "select_*.png"
    item_height = 32
    item_padding = 8
    item_spacing = 8
    icon_width = 0
    icon_height = 0
    item_icon_space = 0
    scrollbar = false
}}

+ image {{ left = {pad} top = 100%-{boot_y} file = "booting-in.png" }}
+ label {{
    id = "__timeout__"
    left = {count_x}
    top = 100%-{count_y}
    width = 80
    height = 16
    align = "left"
    font = "Space Mono Regular 12"
    color = "{secondary}"
    text = "%d s"
}}
+ image {{ left = 100%-{help_x} top = 100%-{help_y} file = "help.png" }}
""".format(black=t["black"], secondary=t["text-secondary"], display=t["text-display"],
           border_visible=t["border-visible"], pad=PAD, pad2=PAD * 2,
           tag_x=PAD + tag_w, menu_x=PAD - 4, bar_w=BAR_W,
           count_x=PAD + boot_w + 16, count_y=PAD + 18, boot_y=PAD + boot_h + 1,
           help_x=PAD + help_w, help_y=PAD + help_h)
    with open(p("theme.txt"), "w") as fh:
        fh.write(theme)

    # The console (c / e) gets a plain black box.
    for piece in ("c", "n", "s", "e", "w", "nw", "ne", "sw", "se"):
        b.rect(p("terminal_%s.png" % piece), 1, 1, t["black"])


if __name__ == "__main__":
    main()
