def index_theme(name, theme):
    return """[Desktop Entry]
Type=X-GNOME-Metatheme
Name=%(name)s
Comment=DOT OS %(cap)s
Encoding=UTF-8

[X-GNOME-Metatheme]
GtkTheme=%(name)s
IconTheme=dot-os%(icon)s
CursorTheme=DotOS-Cursors%(cursor)s
ButtonLayout=:minimize,maximize,close
""" % {"name": name, "cap": CAP[theme], "icon": "" if theme == "dark" else "-light",
       "cursor": "" if theme == "dark" else "-Light"}


def run(tokens):
    made = []
    for theme in THEMES:
        t = tokens[theme]
        name = "DotOS-" + CAP[theme]
        base = "packages/gtk-theme/files/%s/" % name
        variant = "-dark" if theme == "dark" else ""
        gtk3 = (HEADER + '@import url("resource:///org/gtk/libgtk/theme/Adwaita/gtk-contained%s.css");\n'
                % variant + named_colours(t) + rules(t, 3))
        gtk4 = (HEADER + '@import url("resource:///org/gtk/libgtk/theme/Default/Default-%s.css");\n'
                % theme + named_colours(t) + rules(t, 4))
        adw = (HEADER + "/* libadwaita apps ignore GTK themes. Link this file as\n"
               "   ~/.config/gtk-4.0/gtk.css to give them the DOT OS colours. */\n" + named_colours(t)
               + "window, popover > contents, .card { box-shadow: none; }\n"
               + "window.csd { border: 1px solid %s; border-radius: %dpx; }\n" % (t["border-visible"], t["radius-card"])
               + "button { border-radius: %dpx; }\n" % t["radius-pill"]
               + "entry, textview text { caret-color: %s; }\n" % t["accent"])
        made.append(write(base + "gtk-3.0/gtk.css", gtk3))
        made.append(write(base + "gtk-4.0/gtk.css", gtk4))
        made.append(write(base + "gtk-4.0/libadwaita.css", adw))
        made.append(write(base + "index.theme", index_theme(name, theme)))
    return made
