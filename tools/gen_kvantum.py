"""Kvantum theme: a .kvconfig plus an SVG whose element ids Kvantum looks up.

Every element name is prefixed "dot" so nothing is picked up by accident from
Kvantum's built-in default theme. Frames are nine pieces
(<name>-<state>-top|bottom|left|right|topleft|topright|bottomleft|bottomright)
plus an interior (<name>-<state>).

Qt widgets use a 36px control height (the design system's 44px minimum is
kept for the shell, greeter and installer, which are QML).
"""
from tokens import CAP, THEMES, write

STATES = ("normal", "focused", "pressed", "toggled", "disabled")


class Sheet:
    """Lays elements out on a grid; Kvantum only cares about the ids."""

    def __init__(self):
        self.out = []
        self.x = 0
        self.y = 0
        self.row = 0

    def add(self, ident, w, h, body):
        if self.x + w > 1200:
            self.x = 0
            self.y += self.row + 8
            self.row = 0
        # The transparent rect pins the element's bounding box to w x h.
        self.out.append(
            '<g id="%s" transform="translate(%d,%d)"><rect width="%s" height="%s" fill="#000" fill-opacity="0"/>%s</g>'
            % (ident, self.x, self.y, w, h, body))
        self.x += w + 8
        self.row = max(self.row, h)

    def svg(self):
        return ('<?xml version="1.0" encoding="UTF-8"?>\n'
                '<!-- Generated by tools/generate.py from design-system/tokens.json. Do not edit by hand. -->\n'
                '<svg xmlns="http://www.w3.org/2000/svg" width="1220" height="%d" viewBox="0 0 1220 %d">\n%s\n</svg>\n'
                % (self.y + self.row + 8, self.y + self.row + 8, "\n".join(self.out)))


def rect(x, y, w, h, fill):
    return '<rect x="%s" y="%s" width="%s" height="%s" fill="%s"/>' % (x, y, w, h, fill)


def corner(s, r, fill, stroke, sw, top=True, left=True):
    """Top-left corner piece, s x s, radius r. `top`/`left` say which edges carry the border."""
    body = ""
    r = min(r, s)
    if r <= sw:
        if fill:
            body += rect(0, 0, s, s, fill)
        if stroke and top:
            body += rect(0, 0, s, sw, stroke)
        if stroke and left:
            body += rect(0, 0, sw, s, stroke)
        return body
    if fill:
        body += '<path d="M0 %s V%s A%s %s 0 0 1 %s 0 H%s V%s Z" fill="%s"/>' % (s, r, r, r, r, s, s, fill)
    if stroke:
        ri = r - sw
        body += ('<path d="M0 %s V%s A%s %s 0 0 1 %s 0 H%s V%s H%s A%s %s 0 0 0 %s %s V%s Z" fill="%s"/>'
                 % (s, r, r, r, r, s, sw, r, ri, ri, sw, r, s, stroke))
    return body


def frame(sheet, name, state, s, r, fill, stroke, sw=1, sides="tblr", interior=True):
    """Nine-piece frame. `sides` limits which edges are stroked (e.g. "b" for an underline)."""
    pre = "%s-%s" % (name, state) if state else name
    t, b, l, rr = ("t" in sides), ("b" in sides), ("l" in sides), ("r" in sides)
    line = stroke
    flips = {
        "topleft": ("", t, l),
        "topright": ("translate(%s,0) scale(-1,1)" % s, t, rr),
        "bottomleft": ("translate(0,%s) scale(1,-1)" % s, b, l),
        "bottomright": ("translate(%s,%s) scale(-1,-1)" % (s, s), b, rr),
    }
    for pos, (tf, has_h, has_v) in flips.items():
        rounded = has_h and has_v
        body = corner(s, r if rounded else 0, fill, line if (has_h or has_v) else None, sw, has_h, has_v)
        if not rounded and r > sw and fill:
            # square corner on a frame whose other corners are round: keep it square
            pass
        sheet.add("%s-%s" % (pre, pos), s, s, '<g transform="%s">%s</g>' % (tf, body) if tf else body)
    edges = {
        "top": (t, rect(0, 0, s, sw, line or "none")),
        "bottom": (b, rect(0, s - sw, s, sw, line or "none")),
        "left": (l, rect(0, 0, sw, s, line or "none")),
        "right": (rr, rect(s - sw, 0, sw, s, line or "none")),
    }
    for pos, (on, stroke_rect) in edges.items():
        body = rect(0, 0, s, s, fill) if fill else ""
        if on and line:
            body += stroke_rect
        sheet.add("%s-%s" % (pre, pos), s, s, body)
    if interior:
        sheet.add(pre, s, s, rect(0, 0, s, s, fill) if fill else "")


def chevron(direction, colour, size=12, sw=1.5):
    pts = {"down": "3,4.5 6,7.5 9,4.5", "up": "3,7.5 6,4.5 9,7.5",
           "right": "4.5,3 7.5,6 4.5,9", "left": "7.5,3 4.5,6 7.5,9"}[direction]
    return ('<polyline points="%s" fill="none" stroke="%s" stroke-width="%s" stroke-linecap="round" '
            'stroke-linejoin="round"/>' % (pts, colour, sw))


def build_svg(t):
    sh = Sheet()
    none = None
    black, surface, raised = t["black"], t["surface"], t["surface-raised"]
    border, bvis = t["border"], t["border-visible"]
    disabled, secondary, primary, display = t["text-disabled"], t["text-secondary"], t["text-primary"], t["text-display"]

    # Push button: pill outline. Kvantum expands the frame to half the height for
    # controls up to frame.expansion tall and then uses the "expand-" pieces (18px,
    # for the 36px control); taller buttons use the plain 6px pieces.
    for state, fill, stroke in (("normal", none, bvis), ("focused", none, primary), ("pressed", raised, primary),
                                ("toggled", display, display), ("disabled", none, border)):
        frame(sh, "dotbutton", state, 6, 6, fill, stroke)
        frame(sh, "expand-dotbutton", state, 18, 18, fill, stroke)
    # Default button: Kvantum paints <name>-default over the normal frame, so the
    # primary action gets the text-display outline (the fill cannot invert here).
    frame(sh, "dotbutton", "default", 6, 6, none, display)
    frame(sh, "expand-dotbutton", "default", 18, 18, none, display)
    sh.add("button-default-indicator", 8, 8, "")  # hides Kvantum's built-in corner mark
    # Tool button: nothing at rest, outline on hover, inverted when on.
    for state, fill, stroke in (("normal", none, none), ("focused", none, bvis), ("pressed", raised, bvis),
                                ("toggled", display, display), ("disabled", none, none)):
        frame(sh, "dottool", state, 8, 8, fill, stroke)
    # Line edit: underline only.
    for state, stroke in (("normal", bvis), ("focused", display), ("pressed", display), ("toggled", display),
                          ("disabled", border)):
        frame(sh, "dotedit", state, 4, 0, none, stroke, sides="b")
    # Combo box and spin box: radius-compact outline.
    for state, fill, stroke in (("normal", none, bvis), ("focused", none, primary), ("pressed", raised, primary),
                                ("toggled", raised, primary), ("disabled", none, border)):
        frame(sh, "dotcombo", state, 8, 8, fill, stroke)
    # Item views: hover is surface, the current row is surface-raised.
    for state, fill in (("normal", none), ("focused", surface), ("pressed", raised), ("toggled", raised),
                        ("disabled", none)):
        frame(sh, "dotitem", state, 4, 4, fill, none)
    # Menus and tooltips.
    frame(sh, "dotmenu", "normal", 8, 8, raised, bvis)
    for state, fill in (("normal", none), ("focused", display), ("pressed", display), ("toggled", display),
                        ("disabled", none)):
        frame(sh, "dotmenuitem", state, 4, 4, fill, none)
    sh.add("dotmenuitem-separator", 16, 9, rect(0, 4, 16, 1, bvis))
    sh.add("dotmenuitem-tearoff", 16, 9, rect(0, 4, 16, 1, bvis))
    frame(sh, "dottip", "normal", 4, 4, raised, bvis)
    # Menu bar and its items.
    frame(sh, "dotmenubar", "normal", 4, 0, surface, border, sides="b")
    for state, fill in (("normal", none), ("focused", display), ("pressed", display), ("toggled", display),
                        ("disabled", none)):
        frame(sh, "dotmenubaritem", state, 4, 0, fill, none)
    # Tool bar, title bar of docked panels, status bar.
    frame(sh, "dottoolbar", "normal", 4, 0, surface, border, sides="b")
    frame(sh, "dottitlebar", "normal", 4, 0, surface, border, sides="b")
    frame(sh, "dottitlebar", "focused", 4, 0, surface, border, sides="b")
    # Generic frames, tab pane, group box.
    for name in ("dotframe", "dotgroup", "dottabframe"):
        frame(sh, name, "normal", 8, 8, none, border)
        frame(sh, name, "focused", 8, 8, none, bvis)
    # Tabs: text over a 2px underline.
    for state, stroke in (("normal", none), ("focused", bvis), ("pressed", display), ("toggled", display),
                          ("disabled", none)):
        frame(sh, "dottab", state, 4, 0, none, stroke, sw=2, sides="b")
    # Column headers.
    for state, fill in (("normal", black), ("focused", surface), ("pressed", raised), ("toggled", raised),
                        ("disabled", black)):
        frame(sh, "dotheader", state, 4, 0, fill, border, sides="b")
    # Focus ring: 2px text-display.
    frame(sh, "dotfocus", "", 4, 4, none, display, sw=2, interior=False)

    # Scrollbar thumb: 4px square bar inside a 12px lane.
    for state, fill in (("normal", bvis), ("focused", secondary), ("pressed", primary), ("toggled", secondary),
                        ("disabled", border)):
        sh.add("dotscroll-%s" % state, 12, 12, rect(4, 0, 4, 12, fill))
        for pos in ("top", "bottom", "left", "right", "topleft", "topright", "bottomleft", "bottomright"):
            sh.add("dotscroll-%s-%s" % (state, pos), 1, 1, "")
    # Slider: 2px groove, filled part, 16px round handle.
    for state, fill in (("normal", bvis), ("toggled", display), ("disabled", border)):
        sh.add("dotgroove-%s" % state, 8, 2, rect(0, 0, 8, 2, fill))
    for state, fill in (("normal", display), ("focused", display), ("pressed", primary), ("toggled", display),
                        ("disabled", disabled)):
        sh.add("dothandle-%s" % state, 16, 16, '<circle cx="8" cy="8" r="8" fill="%s"/>' % fill)
    # Progress bar: flat trough and a segmented fill (14px block, 2px gap).
    for state, fill in (("normal", border), ("disabled", border)):
        sh.add("dotprogress-%s" % state, 16, 10, rect(0, 0, 16, 10, fill))
    for state, fill in (("normal", display), ("toggled", display), ("disabled", disabled)):
        sh.add("dotprogressfill-%s" % state, 16, 10, rect(0, 0, 14, 10, fill) + rect(14, 0, 2, 10, black))

    # Check box and radio: the mark is a filled block inside the outline.
    def box(shape, stroke, mark, opacity=1.0):
        if shape == "check":
            outer = '<rect x="0.5" y="0.5" width="17" height="17" rx="4" fill="none" stroke="%s"/>' % stroke
            inner = '<rect x="4" y="4" width="10" height="10" rx="1" fill="%s"/>' % mark if mark else ""
            if mark == "dash":
                inner = rect(4, 8, 10, 2, stroke)
        else:
            outer = '<circle cx="9" cy="9" r="8.5" fill="none" stroke="%s"/>' % stroke
            inner = '<circle cx="9" cy="9" r="5" fill="%s"/>' % mark if mark else ""
        return '<g opacity="%s">%s%s</g>' % (opacity, outer, inner)

    for shape, name in (("check", "dotcheck"), ("radio", "dotradio")):
        for state, stroke, opacity in (("normal", secondary, 1), ("focused", display, 1), ("pressed", display, 1),
                                       ("disabled", secondary, 0.4)):
            sh.add("%s-%s" % (name, state), 18, 18, box(shape, stroke, None, opacity))
            sh.add("%s-checked-%s" % (name, state), 18, 18, box(shape, display, display, opacity))
            if shape == "check":
                sh.add("%s-tristate-%s" % (name, state), 18, 18, box(shape, display, "dash", opacity))

    # Arrows (combo, spin, menus, scroll) and tree expanders.
    for state, colour in (("normal", secondary), ("focused", display), ("pressed", display),
                          ("toggled", black), ("disabled", disabled)):
        for direction in ("up", "down", "left", "right"):
            sh.add("dotarrow-%s-%s" % (direction, state), 12, 12, chevron(direction, colour))
        sh.add("dotarrow-plus-%s" % state, 12, 12,
               '<path d="M6 2.5V9.5M2.5 6H9.5" fill="none" stroke="%s" stroke-width="1.5" stroke-linecap="round"/>' % colour)
        sh.add("dotarrow-minus-%s" % state, 12, 12,
               '<path d="M2.5 6H9.5" fill="none" stroke="%s" stroke-width="1.5" stroke-linecap="round"/>' % colour)
        sh.add("dottree-plus-%s" % state, 12, 12, chevron("right", colour))
        sh.add("dottree-minus-%s" % state, 12, 12, chevron("down", colour))
    # Splitter and size grip: a single hairline, nothing else.
    sh.add("dotsplit-normal", 1, 16, rect(0, 0, 1, 16, border))
    sh.add("dotsplit-focused", 1, 16, rect(0, 0, 1, 16, bvis))
    sh.add("dotgrip-normal", 12, 12, "")
    sh.add("dotgrip-focused", 12, 12, "")
    # Dial: an outline ring with a round handle.
    sh.add("dial", 48, 48, '<circle cx="24" cy="24" r="23.5" fill="none" stroke="%s"/>' % bvis)
    sh.add("dial-handle", 12, 12, '<circle cx="6" cy="6" r="6" fill="%s"/>' % display)
    sh.add("dial-notches", 48, 48, "")
    return sh.svg()


